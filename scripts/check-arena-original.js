const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
  const failures=[];
  page.on('pageerror',e=>failures.push(String(e)));
  page.on('requestfailed',r=>failures.push(r.url()));
  await page.goto(process.env.ARENA_URL || 'http://127.0.0.1:8000/arena-batalha.html');
  await page.clock.install();
  await page.clock.pauseAt(new Date(Date.now()+1000));
  await page.locator('#owned-character').selectOption('1');
  await page.getByText('Iniciar batalha',{exact:true}).click();
  const snapshot=()=>page.evaluate(()=>GoghosBattle.snapshot());
  assert.equal(await page.locator('[data-controller=player]').count(),1);
  assert.equal(await page.locator('[data-controller=bot]').count(),7);
  assert.equal(await page.locator('#owned-name').textContent(),'Sam');
  assert.equal(await page.locator('.original-card').count(),8);
  await page.locator('[data-battle-card=red-0]').click();
  await page.locator('.tc-atk').click();
  await page.clock.runFor(700);
  assert.equal(await page.locator('[data-battle-card=red-0] svg text').first().textContent(),'75');
  await page.locator('#queue .last').click();
  assert.match(await page.locator('#inspector h2').textContent(),/Sam/);
  assert.equal(await page.locator('dialog[open],.tc-pop').count(),0);
  await page.locator('[data-slot=ability]').focus();
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#arena-tip').innerText(),/Habilidade/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#arena-tip').isVisible(),false);
  await page.locator('#history').click();
  assert.equal(await page.locator('dialog:modal').count(),0);
  assert((await page.locator('dialog[open]').boundingBox()).width<=300);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'history');
  await page.locator('#help').click();
  await page.locator('[data-battle-card=blue-1]').click();
  assert.equal(await page.locator('dialog[open],.tc-pop').count(),0);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#control').count(),0);
  assert.equal(await page.locator('.card-health').count(),8);
  assert.equal(await page.locator('[data-battle-card=red-0] .card-health text').textContent(),'75');
  await page.clock.runFor(4000);
  assert.equal((await snapshot()).order[(await snapshot()).cursor],'blue-1');
  assert.equal(await page.locator('#basic').count(),0);
  assert.equal(await page.locator('#support-hand button:visible').count(),3);
  assert.equal(await page.locator('#support-hand img[src="assets/arena/mao-vazia.png"]').count(),3);
  assert.equal(await page.locator('#support-free').textContent(),'3/3');
  assert.equal((await snapshot()).supports.blue.length,3);
  await page.locator('[data-battle-card=red-2]').click();
  assert.equal(await page.locator('.tc-atk').count(),0);
  await page.clock.runFor(4000);
  assert.equal((await snapshot()).last,'blue-1');
  await page.waitForFunction(()=>GoghosBattle.snapshot().cards.some(c=>c.team==='blue'&&c.hp===75));
  await page.locator('#pause').click();
  assert(await page.evaluate(()=>GoghosBattle.snapshot().paused));
  await page.locator('#pause').click();
  assert.equal(await page.locator('#owned-name').textContent(),'Sam');
  const legible=await page.locator('[data-controller=player] .card-health').evaluate(el=>{
   const a=el.getBoundingClientRect();
   return [...document.querySelectorAll('#support-hand button')].every(slot=>{
    const b=slot.getBoundingClientRect();return a.bottom<=b.top||b.right<=a.left||b.left>=a.right;
   });
  });
  assert(legible,'Apoios não devem cobrir a vida do jogador');
  const phone=await browser.newPage({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
  await phone.goto(page.url());
  await phone.locator('#owned-character').selectOption('4');
  await phone.getByRole('button',{name:'Iniciar batalha',exact:true}).tap();
  assert.equal(await phone.locator('[data-controller=bot]').count(),7);
  const turnSlot=await phone.locator('#queue .current').elementHandle();
  await phone.locator('[data-battle-card=red-0]').tap();
  await phone.locator('.tc-atk').tap();
  assert.equal(await phone.locator('#inspector h2').textContent(),'Mike');
  assert(await turnSlot.evaluate(el=>el===document.querySelector('#queue .current')));
  await phone.locator('[data-slot=ability]').tap();
  assert.match(await phone.locator('#dialog-body').innerText(),/AK-47/);
  await phone.goto(page.url());
  await phone.emulateMedia({reducedMotion:'no-preference'});
  await phone.locator('#owned-character').selectOption({label:'Nully'});
  await phone.getByRole('button',{name:'Iniciar batalha',exact:true}).tap();
  await phone.locator('[data-battle-card=red-0]').tap();
  await phone.locator('.tc-atk').tap();
  await phone.locator('canvas').waitFor({state:'attached'});
  await phone.waitForFunction(()=>GoghosBattle.snapshot().cards.find(c=>c.id==='red-0').hp===75);
  await phone.locator('canvas').waitFor({state:'detached'});
  assert.equal(await phone.evaluate(()=>GoghosBattle.snapshot().events.filter(e=>e.type==='ataque').length),1);
  await phone.goto(new URL('teste-vida.html',page.url()).href);
  const ribbon=phone.locator('.card-health');
  let previousHp=100;
  for(const hp of [100,75,15,14,0,100]){
   await phone.getByRole('button',{name:hp+'%',exact:true}).tap();
   assert.equal(await ribbon.locator('text').textContent(),String(hp));
   assert.equal(await ribbon.evaluate(el=>el.classList.contains('life-critical')),hp>0&&hp<15);
   assert.equal(await ribbon.evaluate(el=>el.classList.contains('took-damage')),hp<previousHp);
   assert.equal(await ribbon.locator('.life-track').evaluate(el=>getComputedStyle(el).fill),'rgb(66, 36, 54)');
   assert.equal(await ribbon.locator('.damage-trail').evaluate(el=>getComputedStyle(el).fill),'rgb(255, 154, 57)');
   previousHp=hp;
   const masks=await ribbon.locator('clipPath rect').evaluateAll(rects=>rects.map(rect=>Number(rect.getAttribute('x'))/Number(rect.getAttribute('width'))));
   assert.equal(masks.length,2);
   assert(masks.every(edge=>Math.abs(edge-(1-hp/100))<.001));
  }
  await phone.close();
  await page.screenshot({path:'/tmp/arena-original-058.png'});
  assert.deepEqual(failures,[]);
  console.log('PASS seleção, dois times, um jogador e sete bots, dano na arte, bot, fila, pausa e arquivos offline.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
